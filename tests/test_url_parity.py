def test_ams_route_pins_daily_weekdays() -> None:
    """The API path must ignore config weekdays for AMS (legacy behavior)."""
    g = GOLDEN["ams"]
    route = BUILTIN_ROUTES["ams"]
    config = dict(g["params"])
    config["weekdays"] = "Sat,Sun,Tue,Thu"  # ScanCreate default leaks this for every scanner
    assert engine.estimate_pairs(route, config) == g["count"], (
        "AMS estimate must stay daily even when config carries weekdays"
    )


def test_shim_legacy_build_url_signatures() -> None:
    import cheapest_dub_ams as ams
    import cheapest_dub_cai_egyptair as egyptair
    import cheapest_dub_turkey as turkey

    for key, url in GOLDEN["egyptair"]["urls"].items():
        dep, ret = key.split("|")
        assert egyptair.build_url(_d(dep), _d(ret)) == url
    for key, url in GOLDEN["turkey"]["urls"].items():
        dest, dep, ret = key.split("|")
        assert turkey.build_url(_d(dep), _d(ret), dest) == url
    for key, url in GOLDEN["ams"]["urls"].items():
        dep, ret = key.split("|")
        assert ams.build_url(_d(dep), _d(ret)) == url
    assert [d.isoformat() for d, _ in turkey.august_2026_pairs()] == [
        p[0] for p in GOLDEN["turkey"]["pairs"]
    ]


def test_scanner_estimate_total_matches_golden() -> None:
    from app.scanner import estimate_total

    assert estimate_total("egyptair", dict(GOLDEN["egyptair"]["params"])) == GOLDEN["egyptair"]["count"]
    assert estimate_total("turkey", {"destinations": "IST,SAW,AYT"}) == GOLDEN["turkey"]["count"]
    assert estimate_total("ams", dict(GOLDEN["ams"]["params"])) == GOLDEN["ams"]["count"]
    try:
        estimate_total("nope", {})
        raise AssertionError("estimate_total should reject unknown scanner")
    except ValueError as exc:
        assert "Unknown scanner" in str(exc)


if __name__ == "__main__":
    failures = 0
    for name, fn in sorted(globals().items()):
        if name.startswith("test_") and callable(fn):
            try:
                fn()
                print(f"PASS {name}")
            except AssertionError as exc:
                failures += 1
                print(f"FAIL {name}: {exc}")
    sys.exit(1 if failures else 0)
