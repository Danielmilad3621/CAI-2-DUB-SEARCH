"""URL + pair-count parity: engine vs the pre-refactor golden baseline.

Asserts that app.engine reproduces, byte-for-byte, every URL in
tests/golden_urls.json (generated by tests/make_golden.py from the untouched
legacy scrapers), and that pair counts / estimates match. Also exercises the
legacy-signature build_url wrappers on the three shim scripts.

Run standalone (no pytest needed):  .venv/bin/python tests/test_url_parity.py
Or via pytest:                      pytest tests/test_url_parity.py
"""

from __future__ import annotations

import datetime as dt
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app import engine  # noqa: E402
from app.route_defs import BUILTIN_ROUTES  # noqa: E402

GOLDEN = json.loads((ROOT / "tests" / "golden_urls.json").read_text())


def _d(s: str) -> dt.date:
    return dt.date.fromisoformat(s)


def test_egyptair_engine_urls() -> None:
    g = GOLDEN["egyptair"]
    route = BUILTIN_ROUTES["egyptair"]
    config = dict(g["params"])
    pairs = engine.enumerate_pairs(route, config)
    assert len(pairs) == g["count"], f"pair count {len(pairs)} != golden {g['count']}"
    built = {
        f"{dep}|{ret}": engine.build_url(dep, ret, dest="CAI", airline="MS")
        for dep, ret in pairs
    }
    assert built == g["urls"], "egyptair engine URLs diverge from golden"
    assert engine.estimate_pairs(route, config) == g["count"]


def test_turkey_engine_urls() -> None:
    g = GOLDEN["turkey"]
    route = BUILTIN_ROUTES["turkey"]
    config = {"destinations": ",".join(g["destinations"])}
    pairs = engine.enumerate_pairs(route, config)
    assert [[d.isoformat(), r.isoformat()] for d, r in pairs] == g["pairs"], (
        "turkey fixed pairs diverge from golden"
    )
    built = {
        f"{dest}|{dep}|{ret}": engine.build_url(dep, ret, dest=dest, airline=None)
        for dest in g["destinations"]
        for dep, ret in pairs
    }
    assert built == g["urls"], "turkey engine URLs diverge from golden"
    assert engine.estimate_pairs(route, config) == g["count"]
    assert engine.destinations_for(route, config) == tuple(g["destinations"])


